"""Song model: plain data about one song. Contains NO playlist pointers."""
from dataclasses import dataclass


@dataclass(frozen=True)
class Song:
    id: int            # unique, generated by LibraryManager (never typed by the user)
    title: str
    artist: str
    audio_path: str = ""   # location of the audio file on disk

    def to_dict(self) -> dict:
        return {"id": self.id, "title": self.title,
                "artist": self.artist, "audio_path": self.audio_path}

    @staticmethod
    def from_dict(data: dict) -> "Song":
        """Validate and build a Song from saved JSON. Raises ValueError if invalid."""
        if not isinstance(data, dict):
            raise ValueError("song record is not an object")
        song_id = data.get("id")
        if not isinstance(song_id, int) or isinstance(song_id, bool) or song_id < 1:
            raise ValueError(f"invalid song id: {song_id!r}")
        title = str(data.get("title", "")).strip()
        artist = str(data.get("artist", "")).strip()
        if not title or not artist:
            raise ValueError(f"song {song_id} needs a title and an artist")
        return Song(song_id, title, artist, str(data.get("audio_path", "")))
