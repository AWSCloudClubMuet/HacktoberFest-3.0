    public static int seed(TuneWavePlayer player) {
        int added = 0;
        for (int i = 0; i < SONGS.length; i++) {
            if (player.addSong(new Song("s" + (i + 1), SONGS[i][0], SONGS[i][1]))) {
                added++;
            }
        }
        for (int i = 0; i < RELATIONS.length; i++) {
            player.addRelation(RELATIONS[i][0], RELATIONS[i][1]);
        }
        return added;
    }

    public static int size() {
        return SONGS.length;
    }
