export function getGigCover(gig) {
  if (!gig) return CATEGORY_FALLBACK_COVERS.Programming;
  return GIG_COVERS[gig.id] || CATEGORY_FALLBACK_COVERS[gig.category] || CATEGORY_FALLBACK_COVERS.Programming;
}

export function getUserAvatar(userId) {
  return USER_AVATARS[userId] || 'https://images.unsplash.com/photo-1535713875002-d1d0cf377fde?auto=format&fit=crop&w=256&q=80';
}

